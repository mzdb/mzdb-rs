//! mzdb2peakeldb - Detect MS1 peakels from mzDB files and export to peakelDB format
//!
//! This command-line tool extracts chromatographic peaks (peakels) from MS1 spectra
//! in mzDB files and exports them to a peakelDB SQLite database for downstream analysis.
//!
//! # Usage
//!
//! ```bash
//! mzdb2peakeldb input.mzDB output.peakeldb [options]
//! ```
//!
//! # Options
//!
//! - `--mz-tol <PPM>`: m/z tolerance in ppm for XIC extraction (default: 10)
//! - `--min-peaks <N>`: Minimum peaks per peakel (default: 5)
//! - `--intensity-percentile <F>`: Intensity percentile threshold (default: 0.9)

use std::env;
use std::path::Path;
use std::process;

use anyhow::{Context, Result};
use rusqlite::{Connection, params};

use mzdb::MzDbReader;

#[cfg(feature = "processing")]
use mzdb::processing::{
    SmartPeakelFinder, SmartPeakelFinderConfig, PeakelFinder,
    Peakel,
};

/// Configuration for peakel detection
#[derive(Debug, Clone)]
pub struct PeakelDetectionConfig {
    /// m/z tolerance in ppm for XIC extraction
    pub mz_tol_ppm: f64,
    /// Minimum number of peaks per peakel
    pub min_peaks_count: usize,
    /// Intensity percentile threshold (0.0-1.0)
    pub intensity_percentile: f32,
    /// Maximum consecutive gaps allowed in a peakel
    pub max_consecutive_gaps: usize,
    /// Maximum time window for peakel extraction (seconds)
    pub max_time_window: f32,
}

impl Default for PeakelDetectionConfig {
    fn default() -> Self {
        Self {
            mz_tol_ppm: 10.0,
            min_peaks_count: 5,
            intensity_percentile: 0.9,
            max_consecutive_gaps: 3,
            max_time_window: 1200.0,
        }
    }
}

/// PeakelDB writer for storing detected peakels
pub struct PeakelDbWriter {
    connection: Connection,
    peakel_count: usize,
}

impl PeakelDbWriter {
    /// Create a new peakelDB file
    pub fn create<P: AsRef<Path>>(path: P, mzdb_filename: &str) -> Result<Self> {
        let conn = Connection::open(path.as_ref())
            .context("Failed to create peakelDB file")?;

        // SQLite optimizations
        conn.execute_batch(
            "PRAGMA synchronous=OFF;
             PRAGMA journal_mode=OFF;
             PRAGMA temp_store=2;
             PRAGMA cache_size=100000;"
        )?;

        // Create schema
        conn.execute_batch(PEAKELDB_SCHEMA)?;

        // Insert peakeldb_file record
        let now = chrono_lite_timestamp();
        conn.execute(
            "INSERT INTO peakeldb_file (id, name, description, raw_file_name, is_dia_experiment, 
             creation_timestamp, modification_timestamp) VALUES (?, ?, ?, ?, ?, ?, ?)",
            params![1, mzdb_filename, "Generated by mzdb2peakeldb", mzdb_filename, false, &now, &now],
        )?;

        // Insert lcms_map record
        conn.execute(
            "INSERT INTO lcms_map (id, ms_level, peakel_count, peakeldb_file_id) VALUES (?, ?, ?, ?)",
            params![1, 1, 0, 1],
        )?;

        Ok(Self {
            connection: conn,
            peakel_count: 0,
        })
    }

    #[cfg(feature = "processing")]
    /// Insert a peakel into the database
    pub fn insert_peakel(&mut self, peakel: &Peakel) -> Result<()> {
        self.peakel_count += 1;
        let peakel_id = self.peakel_count as i64;

        // Calculate peakel properties
        let mz = peakel.calc_mz();
        let elution_time = peakel.apex_elution_time();
        let duration = peakel.calc_duration();
        let apex_intensity = peakel.apex_intensity();
        let area = peakel.area();
        let peak_count = peakel.peaks_count() as i32;
        
        // Calculate min/max values for R-tree
        let min_mz = peakel.mz_values.iter().cloned().fold(f64::INFINITY, f64::min);
        let max_mz = peakel.mz_values.iter().cloned().fold(f64::NEG_INFINITY, f64::max);
        let min_time = peakel.elution_times.iter().cloned().fold(f32::INFINITY, f32::min);
        let max_time = peakel.elution_times.iter().cloned().fold(f32::NEG_INFINITY, f32::max);

        // Serialize peak data as MessagePack-like binary (simplified version)
        let peaks_blob = serialize_peakel_data(peakel)?;

        // Calculate HWHM statistics
        let left_hwhm_mean = peakel.left_hwhm_mean();
        let right_hwhm_mean = peakel.right_hwhm_mean();

        // Get spectrum IDs
        let first_spectrum_id = peakel.spectrum_ids.first().copied().unwrap_or(0);
        let apex_spectrum_id = peakel.apex_spectrum_id();
        let last_spectrum_id = peakel.spectrum_ids.last().copied().unwrap_or(0);

        // Insert into peakel table
        self.connection.execute(
            "INSERT INTO peakel (id, moz, elution_time, duration, gap_count, apex_intensity, area,
             amplitude, intensity_cv, left_hwhm_mean, left_hwhm_cv, right_hwhm_mean, right_hwhm_cv,
             peak_count, peaks, first_spectrum_id, apex_spectrum_id, last_spectrum_id, 
             is_selected, serialized_properties, map_id)
             VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
            params![
                peakel_id,
                mz,
                elution_time,
                duration,
                0, // gap_count - simplified
                apex_intensity,
                area,
                apex_intensity / peakel.intensity_values.iter().cloned().fold(f32::INFINITY, f32::min).max(1.0), // amplitude
                0.0, // intensity_cv - simplified
                left_hwhm_mean,
                0.0, // left_hwhm_cv
                right_hwhm_mean,
                0.0, // right_hwhm_cv
                peak_count,
                peaks_blob,
                first_spectrum_id,
                apex_spectrum_id,
                last_spectrum_id,
                false, // is_selected
                Option::<String>::None, // serialized_properties
                1, // map_id
            ],
        )?;

        // Insert into R-tree index
        self.connection.execute(
            "INSERT INTO peakel_rtree (id, min_mz, max_mz, min_time, max_time, min_intensity, max_intensity)
             VALUES (?, ?, ?, ?, ?, ?, ?)",
            params![
                peakel_id,
                min_mz,
                max_mz,
                min_time,
                max_time,
                peakel.intensity_values.iter().cloned().fold(f32::INFINITY, f32::min) as f64,
                apex_intensity as f64,
            ],
        )?;

        Ok(())
    }

    /// Finalize the peakelDB file
    pub fn finalize(self) -> Result<usize> {
        // Update peakel count in lcms_map
        self.connection.execute(
            "UPDATE lcms_map SET peakel_count = ? WHERE id = 1",
            params![self.peakel_count as i32],
        )?;

        // Commit and close
        self.connection.execute_batch("PRAGMA optimize;")?;
        
        Ok(self.peakel_count)
    }
}

/// Serialize peakel data to binary format (simplified MessagePack-like format)
#[cfg(feature = "processing")]
fn serialize_peakel_data(peakel: &Peakel) -> Result<Vec<u8>> {
    // Simple binary format: 
    // [n_peaks: u32][spectrum_ids: i64 * n][times: f32 * n][mzs: f64 * n][intensities: f32 * n]
    let n = peakel.peaks_count();
    let mut data = Vec::with_capacity(4 + n * (8 + 4 + 8 + 4));
    
    // Write peak count
    data.extend_from_slice(&(n as u32).to_le_bytes());
    
    // Write spectrum IDs
    for &id in &peakel.spectrum_ids {
        data.extend_from_slice(&id.to_le_bytes());
    }
    
    // Write elution times
    for &time in &peakel.elution_times {
        data.extend_from_slice(&time.to_le_bytes());
    }
    
    // Write m/z values
    for &mz in &peakel.mz_values {
        data.extend_from_slice(&mz.to_le_bytes());
    }
    
    // Write intensities
    for &intensity in &peakel.intensity_values {
        data.extend_from_slice(&intensity.to_le_bytes());
    }
    
    Ok(data)
}

/// Simple timestamp function (ISO format)
fn chrono_lite_timestamp() -> String {
    use std::time::{SystemTime, UNIX_EPOCH};
    let duration = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default();
    let secs = duration.as_secs();
    // Convert to a simple timestamp format
    format!("{}", secs)
}

/// PeakelDB SQLite schema
const PEAKELDB_SCHEMA: &str = r#"
CREATE TABLE peakeldb_file (
    id INTEGER NOT NULL PRIMARY KEY,
    name VARCHAR NOT NULL,
    description VARCHAR,
    raw_file_name VARCHAR NOT NULL,
    is_dia_experiment BOOLEAN NOT NULL,
    creation_timestamp VARCHAR NOT NULL,
    modification_timestamp VARCHAR NOT NULL,
    serialized_properties TEXT
);

CREATE TABLE lcms_map (
    id INTEGER NOT NULL PRIMARY KEY,
    ms_level INTEGER NOT NULL,
    peakel_count INTEGER NOT NULL,
    serialized_properties TEXT,
    peakeldb_file_id INTEGER NOT NULL,
    FOREIGN KEY (peakeldb_file_id) REFERENCES peakeldb_file (id)
);

CREATE TABLE peakel (
    id INTEGER NOT NULL PRIMARY KEY,
    moz REAL NOT NULL,
    elution_time REAL NOT NULL,
    duration REAL NOT NULL,
    gap_count INTEGER NOT NULL,
    apex_intensity REAL NOT NULL,
    area REAL NOT NULL,
    amplitude REAL NOT NULL,
    intensity_cv REAL NOT NULL,
    left_hwhm_mean REAL NOT NULL,
    left_hwhm_cv REAL NOT NULL,
    right_hwhm_mean REAL NOT NULL,
    right_hwhm_cv REAL NOT NULL,
    peak_count INTEGER NOT NULL,
    peaks BLOB NOT NULL,
    first_spectrum_id INTEGER NOT NULL,
    apex_spectrum_id INTEGER NOT NULL,
    last_spectrum_id INTEGER NOT NULL,
    is_selected BOOLEAN NOT NULL DEFAULT 0,
    serialized_properties TEXT,
    map_id INTEGER NOT NULL,
    FOREIGN KEY (map_id) REFERENCES lcms_map (id)
);

CREATE VIRTUAL TABLE peakel_rtree USING rtree(
    id,
    min_mz, max_mz,
    min_time, max_time,
    min_intensity, max_intensity
);

CREATE INDEX peakel_moz_idx ON peakel (moz);
CREATE INDEX peakel_elution_time_idx ON peakel (elution_time);
CREATE INDEX peakel_map_id_idx ON peakel (map_id);
"#;

fn print_usage(program: &str) {
    eprintln!("Usage: {} <input.mzDB> <output.peakeldb> [options]", program);
    eprintln!();
    eprintln!("Options:");
    eprintln!("  --mz-tol <PPM>           m/z tolerance in ppm (default: 10)");
    eprintln!("  --min-peaks <N>          Minimum peaks per peakel (default: 5)");
    eprintln!("  --intensity-pct <F>      Intensity percentile threshold 0-1 (default: 0.9)");
    eprintln!("  --max-gaps <N>           Maximum consecutive gaps (default: 3)");
    eprintln!("  -h, --help               Show this help message");
}

#[cfg(feature = "processing")]
fn detect_peakels_from_mzdb(
    mzdb: &MzDbReader,
    config: &PeakelDetectionConfig,
) -> Result<Vec<Peakel>> {
    use std::collections::BTreeMap;
    
    println!("Detecting MS1 peakels...");
    
    // Get MS1 spectrum headers sorted by time
    let headers = mzdb.get_spectrum_headers();
    let ms1_headers: Vec<_> = headers.iter()
        .filter(|h| h.ms_level == 1)
        .collect();
    
    println!("  Found {} MS1 spectra", ms1_headers.len());
    
    if ms1_headers.is_empty() {
        return Ok(vec![]);
    }
    
    // Build a map of all peaks organized by approximate m/z bins
    // This is a simplified version of the full peakel detection algorithm
    let mz_bin_size = config.mz_tol_ppm * 0.001; // Convert ppm to approximate bin size at m/z ~1000
    
    // Collect all peaks from MS1 spectra
    println!("  Collecting peaks from MS1 spectra...");
    let mut peaks_by_mz_bin: BTreeMap<i64, Vec<(f64, f32, i64, f32)>> = BTreeMap::new(); // (mz, intensity, spectrum_id, rt)
    
    for header in &ms1_headers {
        let spectrum = mzdb.get_spectrum(header.id)
            .with_context(|| format!("Failed to read spectrum {}", header.id))?;
        
        let rt = header.time * 60.0; // Convert to seconds
        
        for (&mz, &intensity) in spectrum.data.mz_array.iter().zip(spectrum.data.intensity_array.iter()) {
            let bin = (mz / mz_bin_size) as i64;
            peaks_by_mz_bin.entry(bin)
                .or_default()
                .push((mz, intensity, header.id, rt));
        }
    }
    
    println!("  Found {} m/z bins with peaks", peaks_by_mz_bin.len());
    
    // Create peakel finder
    let finder_config = SmartPeakelFinderConfig {
        min_peaks_count: config.min_peaks_count,
        use_smoothing: true,
        use_baseline_remover: false,
        ..Default::default()
    };
    let finder = SmartPeakelFinder::with_config(finder_config);
    
    // Process each m/z bin to find peakels
    println!("  Detecting peakels in each m/z bin...");
    let mut all_peakels = Vec::new();
    let mut bins_processed = 0;
    let total_bins = peaks_by_mz_bin.len();
    
    for (_bin, mut peaks) in peaks_by_mz_bin {
        bins_processed += 1;
        if bins_processed % 10000 == 0 {
            println!("    Processed {}/{} bins, found {} peakels so far", 
                bins_processed, total_bins, all_peakels.len());
        }
        
        // Skip bins with too few peaks
        if peaks.len() < config.min_peaks_count {
            continue;
        }
        
        // Sort peaks by retention time
        peaks.sort_by(|a, b| a.3.partial_cmp(&b.3).unwrap());
        
        // Build RT-intensity pairs for peakel detection
        let rt_int_pairs: Vec<(f32, f64)> = peaks.iter()
            .map(|&(_, intensity, _, rt)| (rt, intensity as f64))
            .collect();
        
        // Find peakels
        let peakel_indices = finder.find_peakels_indices(&rt_int_pairs);
        
        // Convert detected indices to Peakel objects
        for (start, end) in peakel_indices {
            if end - start + 1 < config.min_peaks_count {
                continue;
            }
            
            let peakel_peaks = &peaks[start..=end];
            
            let spectrum_ids: Vec<i64> = peakel_peaks.iter().map(|p| p.2).collect();
            let elution_times: Vec<f32> = peakel_peaks.iter().map(|p| p.3).collect();
            let mz_values: Vec<f64> = peakel_peaks.iter().map(|p| p.0).collect();
            let intensity_values: Vec<f32> = peakel_peaks.iter().map(|p| p.1).collect();
            
            let peakel = Peakel::new(
                spectrum_ids,
                elution_times,
                mz_values,
                intensity_values,
                None,
                None,
            );
            
            all_peakels.push(peakel);
        }
    }
    
    println!("  Detected {} peakels total", all_peakels.len());
    
    Ok(all_peakels)
}

#[cfg(not(feature = "processing"))]
fn detect_peakels_from_mzdb(
    _mzdb: &MzDbReader,
    _config: &PeakelDetectionConfig,
) -> Result<Vec<()>> {
    eprintln!("Error: The 'processing' feature is required for peakel detection.");
    eprintln!("Please rebuild with: cargo build --features processing");
    process::exit(1);
}

fn main() {
    let args: Vec<String> = env::args().collect();
    let program = &args[0];

    if args.len() < 3 {
        print_usage(program);
        process::exit(1);
    }

    // Check for help flag
    if args.iter().any(|a| a == "-h" || a == "--help") {
        print_usage(program);
        process::exit(0);
    }

    let input_path = &args[1];
    let output_path = &args[2];

    // Parse options
    let mut config = PeakelDetectionConfig::default();
    let mut i = 3;
    while i < args.len() {
        match args[i].as_str() {
            "--mz-tol" => {
                i += 1;
                if i >= args.len() {
                    eprintln!("Error: --mz-tol requires a value");
                    process::exit(1);
                }
                match args[i].parse::<f64>() {
                    Ok(v) => config.mz_tol_ppm = v,
                    Err(_) => {
                        eprintln!("Error: Invalid mz-tol value: {}", args[i]);
                        process::exit(1);
                    }
                }
            }
            "--min-peaks" => {
                i += 1;
                if i >= args.len() {
                    eprintln!("Error: --min-peaks requires a value");
                    process::exit(1);
                }
                match args[i].parse::<usize>() {
                    Ok(v) => config.min_peaks_count = v,
                    Err(_) => {
                        eprintln!("Error: Invalid min-peaks value: {}", args[i]);
                        process::exit(1);
                    }
                }
            }
            "--intensity-pct" => {
                i += 1;
                if i >= args.len() {
                    eprintln!("Error: --intensity-pct requires a value");
                    process::exit(1);
                }
                match args[i].parse::<f32>() {
                    Ok(v) => config.intensity_percentile = v,
                    Err(_) => {
                        eprintln!("Error: Invalid intensity-pct value: {}", args[i]);
                        process::exit(1);
                    }
                }
            }
            "--max-gaps" => {
                i += 1;
                if i >= args.len() {
                    eprintln!("Error: --max-gaps requires a value");
                    process::exit(1);
                }
                match args[i].parse::<usize>() {
                    Ok(v) => config.max_consecutive_gaps = v,
                    Err(_) => {
                        eprintln!("Error: Invalid max-gaps value: {}", args[i]);
                        process::exit(1);
                    }
                }
            }
            arg => {
                eprintln!("Error: Unknown option: {}", arg);
                print_usage(program);
                process::exit(1);
            }
        }
        i += 1;
    }

    // Open mzDB file
    println!("Opening mzDB file: {}", input_path);
    let mzdb = match MzDbReader::open(input_path) {
        Ok(db) => db,
        Err(e) => {
            eprintln!("Error opening mzDB file: {}", e);
            process::exit(1);
        }
    };

    // Detect peakels
    #[cfg(feature = "processing")]
    {
        let peakels = match detect_peakels_from_mzdb(&mzdb, &config) {
            Ok(p) => p,
            Err(e) => {
                eprintln!("Error detecting peakels: {}", e);
                process::exit(1);
            }
        };

        if peakels.is_empty() {
            println!("No peakels detected. Check if the file contains MS1 data.");
            process::exit(0);
        }

        // Get input filename for metadata
        let input_filename = Path::new(input_path)
            .file_name()
            .and_then(|n| n.to_str())
            .unwrap_or("unknown.mzDB");

        // Create peakelDB and write peakels
        println!("Creating peakelDB: {}", output_path);
        let mut writer = match PeakelDbWriter::create(output_path, input_filename) {
            Ok(w) => w,
            Err(e) => {
                eprintln!("Error creating peakelDB file: {}", e);
                process::exit(1);
            }
        };

        println!("Writing {} peakels...", peakels.len());
        for peakel in &peakels {
            if let Err(e) = writer.insert_peakel(peakel) {
                eprintln!("Error writing peakel: {}", e);
                process::exit(1);
            }
        }

        match writer.finalize() {
            Ok(count) => {
                println!("Successfully wrote {} peakels to peakelDB", count);
            }
            Err(e) => {
                eprintln!("Error finalizing peakelDB: {}", e);
                process::exit(1);
            }
        }
    }

    #[cfg(not(feature = "processing"))]
    {
        eprintln!("Error: The 'processing' feature is required for peakel detection.");
        eprintln!("Please rebuild with: cargo build --features processing");
        process::exit(1);
    }
}
