//! shrinkdia - Shrink/Simplify DIA mzDB files using detected MS2 peakels
//!
//! This command-line tool simplifies DIA (Data-Independent Acquisition) mzDB files
//! by reconstructing MS2 spectra from detected peakels. For each peakel, only the
//! apex and surrounding data points are retained, significantly reducing file size
//! while preserving the essential signal information.
//!
//! # Usage
//!
//! ```bash
//! shrinkdia --mzdb input.mzDB --peakeldb peakels.peakeldb --output output.mzDB [options]
//! ```
//!
//! # Required Arguments
//!
//! - `--mzdb, -m <FILE>`: Input DIA mzDB file
//! - `--peakeldb, -p <FILE>`: Input MS2 peakeldb file (from mzdb2peakeldb)
//! - `--output, -o <FILE>`: Output simplified DIA mzDB file
//!
//! # Options
//!
//! - `--points <N>`: Number of data points to retain per peakel (must be odd, default: 3)
//! - `-v, --verbose`: Enable verbose output
//!
//! # Example
//!
//! ```bash
//! # First detect peakels
//! mzdb2peakeldb --input dia_file.mzDB --output peakels.peakeldb --ms-level 2
//!
//! # Then simplify the DIA file
//! shrinkdia -m dia_file.mzDB -p peakels.peakeldb -o simplified.mzDB --points 3
//! ```

use std::path::PathBuf;
use std::process;

use clap::Parser;

use mzdb::processing::dia_simplifier::{DiaSimplifier, DiaSimplifierConfig};

/// Shrink DIA mzDB files using detected MS2 peakels
#[derive(Parser, Debug)]
#[command(
    name = "shrinkdia",
    author = "mzdb-rs",
    version,
    about = "Shrink/Simplify DIA mzDB files using detected MS2 peakels",
    long_about = "This tool simplifies DIA (Data-Independent Acquisition) mzDB files by \
                  reconstructing MS2 spectra from detected peakels. For each peakel, only \
                  the apex and surrounding data points are retained, significantly reducing \
                  file size while preserving the essential signal information."
)]
struct Args {
    /// Input DIA mzDB file
    #[arg(short, long)]
    mzdb: PathBuf,

    /// Input MS2 peakeldb file (generated by mzdb2peakeldb with --ms-level 2)
    #[arg(short, long)]
    peakeldb: PathBuf,

    /// Output simplified DIA mzDB file
    #[arg(short, long)]
    output: PathBuf,

    /// Number of data points to retain per peakel (centered on apex).
    /// Must be odd (1, 3, 5, etc.).
    #[arg(long, default_value_t = 3)]
    points: usize,

    /// Enable verbose output
    #[arg(short, long)]
    verbose: bool,
}

fn main() {
    let args = Args::parse();

    // Initialize logging
    if args.verbose {
        env_logger::Builder::from_env(
            env_logger::Env::default().default_filter_or("debug"),
        )
        .init();
    } else {
        env_logger::Builder::from_env(
            env_logger::Env::default().default_filter_or("info"),
        )
        .init();
    }

    // Validate inputs
    if !args.mzdb.exists() {
        eprintln!("Error: Input mzDB file not found: {:?}", args.mzdb);
        process::exit(1);
    }

    if !args.peakeldb.exists() {
        eprintln!("Error: Input peakeldb file not found: {:?}", args.peakeldb);
        process::exit(1);
    }

    if args.points % 2 == 0 {
        eprintln!("Error: --points must be odd (1, 3, 5, etc.), got {}", args.points);
        process::exit(1);
    }

    // Create configuration
    let config = match DiaSimplifierConfig::with_points(args.points) {
        Ok(c) => c,
        Err(e) => {
            eprintln!("Error: Invalid configuration: {}", e);
            process::exit(1);
        }
    };

    // Run simplification
    let simplifier = DiaSimplifier::new(config);

    let mzdb_path = args.mzdb.to_str().unwrap_or_default();
    let peakeldb_path = args.peakeldb.to_str().unwrap_or_default();

    match simplifier.simplify(mzdb_path, peakeldb_path, &args.output) {
        Ok(stats) => {
            println!("\n=== Simplification Complete ===");
            println!("Peakels processed: {}", stats.peakel_count);
            println!("Original MS2 spectra: {}", stats.original_ms2_count);
            println!("Simplified MS2 spectra: {}", stats.simplified_ms2_count);
            println!("Data points extracted: {}", stats.data_point_count);
            println!("Output file: {:?}", args.output);
            
            // Calculate reduction
            if stats.original_ms2_count > 0 {
                let reduction = 100.0 * (1.0 - stats.simplified_ms2_count as f64 / stats.original_ms2_count as f64);
                println!("Spectrum count reduction: {:.1}%", reduction);
            }
        }
        Err(e) => {
            eprintln!("Error during simplification: {}", e);
            process::exit(1);
        }
    }
}
